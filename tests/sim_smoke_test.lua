T.test("a logged-out client goes silent and shows offline to its group", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  pok:slash("net")
  vel:slash("net")
  sim:advance(1)
  group(sim, pok, vel)
  local got = recorder(vel, { "UNIT_CONNECTION" })
  sim:logout(pok)
  T.eq(got, { { "UNIT_CONNECTION", "party1", false } })
  T.ok(not vel.env.UnitIsConnected("party1"))
  T.eq(#pok.timers, 0)
  vel.env.C_ChatInfo.SendAddonMessage("PTX", "PING|1|Velvet|Horde", "WHISPER", "Thalindra Forever")
  sim:advance(3)
  T.eq(sim.dropped[#sim.dropped].target, "Thalindra Forever")
end)

