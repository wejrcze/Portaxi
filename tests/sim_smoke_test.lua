T.test("factionSplit decides whether the other faction hears the channel", function()
  for _, split in ipairs({ false, true }) do
    local sim = Sim.new({ factionSplit = split })
    local pok, vel = horde(sim)
    local ali = sim:client("Aldric", { faction = "Alliance", race = "Human", zone = "Stormwind" })
    pok:slash("net")
    vel:slash("net")
    ali:slash("net")
    sim:advance(3)
    T.eq(logHas(ali, "PING|1|Thalindra|Horde"), not split, "Alliance hears Horde, split=" .. tostring(split))
    T.eq(logHas(pok, "PING|1|Aldric|Alliance"), not split, "Horde hears Alliance, split=" .. tostring(split))
    T.ok(logHas(ali, "received CHANNEL from Aldric Forever"), "own echo either way")
    T.ok(logHas(pok, "PING|1|Velvet|Horde"), "same faction either way")
  end
end)

T.test("secure click: scroll to party1, then a portal the rider takes", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  group(sim, pok, vel)
  local pokEvents = recorder(pok, { "UNIT_SPELLCAST_START", "UNIT_SPELLCAST_SUCCEEDED", "ZONE_CHANGED_NEW_AREA" })
  local velEvents = recorder(vel, { "UNIT_SPELLCAST_START", "UNIT_SPELLCAST_SUCCEEDED", "ZONE_CHANGED_NEW_AREA" })
  local b = pok.env.CreateFrame("Button", "PortaxiNextButton", pok.env.UIParent, "SecureActionButtonTemplate")
  b:SetAttribute("type", "item")
  b:SetAttribute("item", SCROLL)
  b:SetAttribute("unit", "party1")

  local click, result = sim:click(pok)
  T.eq(click, { type = "item", item = SCROLL, unit = "party1" })
  T.eq(result, "cast")
  T.eq(pokEvents[1][1], "UNIT_SPELLCAST_START")
  T.eq(pokEvents[1][2], "player")
  T.eq(velEvents[1][1], "UNIT_SPELLCAST_START")
  T.eq(velEvents[1][2], "party1")
  T.eq(velEvents[1][3], pokEvents[1][3], "same castGUID on both sides")
  T.eq(select(2, sim:click(pok)), "busy", "one cast at a time")
  T.ok(vel.env.UnitCastingInfo("party1"), "the rider sees the cast bar")
  T.ok(pok.env.UnitCastingInfo("player"))
  sim:advance(9.9)
  T.eq(#velEvents, 1, "not finished before castTime.scroll")
  sim:advance(0.2)
  T.eq(pokEvents[2][1], "UNIT_SPELLCAST_SUCCEEDED")
  T.eq(pokEvents[2][2], "player")
  T.eq(velEvents[2][1], "UNIT_SPELLCAST_SUCCEEDED")
  T.eq(velEvents[2][2], "party1")
  T.eq(vel.env.UnitCastingInfo("party1"), nil)
  T.eq(pok.player.zone, "Undercity")
  T.eq(pok.player.subzone, "Trade Quarter")
  T.eq(pokEvents[3], { "ZONE_CHANGED_NEW_AREA" })
  T.ok(pok.env.CheckInteractDistance("party1", 2))
  T.ok(vel.env.CheckInteractDistance("party1", 2))
  T.eq(pok.player.items[SCROLL], 8, "one scroll used")

  b:SetAttribute("type", "spell")
  b:SetAttribute("spell", 11417)
  b:SetAttribute("item", nil)
  b:SetAttribute("unit", nil)
  T.eq(select(2, sim:click(pok)), "cast")
  T.fails(function() sim:takePortal(vel, "OG") end, "no open portal", "not before the cast ends")
  sim:advance(10)
  T.eq(pok.player.items[RUNE], 6, "one rune used")
  T.fails(function() sim:takePortal(vel, "UC") end, "no open portal to UC")
  sim:takePortal(vel, "OG")
  T.eq(vel.player.zone, "Orgrimmar")
  T.eq(velEvents[#velEvents], { "ZONE_CHANGED_NEW_AREA" })
  T.ok(not pok.env.CheckInteractDistance("party1", 2), "no longer near")
end)

T.test("a portal closes after Const.T.PORTAL and only serves the group", function()
  local sim = Sim.new({ castTime = { portal = 1 } })
  local pok, vel = horde(sim)
  local ali = sim:client("Aldric", { zone = "Orgrimmar" })
  group(sim, pok, vel)
  local b = pok.env.CreateFrame("Button", "PortaxiNextButton", pok.env.UIParent, "SecureActionButtonTemplate")
  b:SetAttribute("type", "spell")
  b:SetAttribute("spell", 11418)
  sim:click(pok)
  sim:advance(1)
  T.eq(#sim.portals, 1)
  T.fails(function() sim:takePortal(ali, "UC") end, "no open portal", "not in the caster's group")
  T.fails(function() sim:takePortal(vel, "UC") end, "no open portal", "not where the portal stands")
  sim:advance(sim.Const.T.PORTAL)
  T.fails(function() sim:takePortal(pok, "UC") end, "no open portal", "expired")
end)

T.test("other secure clicks are recorded and do nothing; interrupts end the cast", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  local b = pok.env.CreateFrame("Button", "PortaxiNextButton", pok.env.UIParent, "SecureActionButtonTemplate")
  b:SetAttribute("type", "macro")
  b:SetAttribute("macrotext", "/dance")
  T.eq(select(2, sim:click(pok)), "ignored")
  T.eq(sim.clicks[1].click.type, "macro")
  b:SetAttribute("type", "item")
  b:SetAttribute("item", SCROLL)
  b:SetAttribute("unit", "party1")
  T.eq(select(2, sim:click(pok)), "no partner")
  group(sim, pok, vel)
  vel:setResting(false)
  T.eq(select(2, sim:click(pok)), "partner not resting")
  vel:setResting(true)
  local velEvents = recorder(vel, { "UNIT_SPELLCAST_INTERRUPTED", "UNIT_SPELLCAST_SUCCEEDED" })
  T.eq(select(2, sim:click(pok)), "cast")
  sim:advance(5)
  T.ok(sim:interrupt(pok))
  sim:advance(10)
  T.eq(#velEvents, 1)
  T.eq(velEvents[1][1], "UNIT_SPELLCAST_INTERRUPTED")
  T.eq(pok.player.zone, "Orgrimmar", "did not move")
  T.eq(pok.player.items[SCROLL], 9, "scroll kept")
  T.fails(function() sim:click(pok, "NoSuchButton") end, "no button")
end)

T.test("timers of all clients run in global time order on one shared clock", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  local seq = {}
  local function rec(wow, tag)
    return function() seq[#seq + 1] = ("%s@%g/%g"):format(tag, wow.env.GetTime() - 1000, pok.env.GetTime() - 1000) end
  end
  pok.env.C_Timer.After(2, rec(pok, "p2"))
  vel.env.C_Timer.After(1, function()
    rec(vel, "v1")()
    pok.env.C_Timer.After(0.5, rec(pok, "p1.5"))
  end)
  pok.env.C_Timer.After(3, rec(pok, "p3"))
  vel.env.C_Timer.After(2.5, rec(vel, "v2.5"))
  vel.env.C_Timer.After(2, rec(vel, "v2"))
  sim:advance(2.9)
  T.eq(seq, { "v1@1/1", "p1.5@1.5/1.5", "p2@2/2", "v2@2/2", "v2.5@2.5/2.5" })
  sim:advance(0.1)
  T.eq(seq[6], "p3@3/3")
  T.eq(pok.clock, vel.clock)
  T.eq(sim:now(), 1003)
end)

