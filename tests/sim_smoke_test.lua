-- The multi-client simulator (tests/lib/sim.lua), driven through the phase 0 probes (Core/Probe.lua).
local T = dofile("tests/lib/t.lua")
local Sim = dofile("tests/lib/sim.lua")

local SCROLL = 213548
local RUNE = 17032

local function logHas(wow, text)
  local probe = wow.env.PortaxiDB.probe
  for _, e in ipairs(probe and probe.log or {}) do
    if e.text:find(text, 1, true) then return true end
  end
  return false
end

local function sentCount(wow, pattern, target)
  local n = 0
  for _, s in ipairs(wow.sent) do
    if s.msg:find(pattern) and (target == nil or s.target == target) then n = n + 1 end
  end
  return n
end

-- Records the given events of one client as { event, arg1, arg2, ... }.
local function recorder(wow, events)
  local got = {}
  local f = wow.env.CreateFrame("Frame")
  for _, e in ipairs(events) do f:RegisterEvent(e) end
  f:SetScript("OnEvent", function(_, event, ...) got[#got + 1] = { event, ... } end)
  return got
end

local function horde(sim)
  local pok = sim:client("Thalindra")
  local vel = sim:client("Velvet", { class = "WARRIOR", race = "Troll", zone = "Undercity", subzone = "Trade Quarter",
    mapId = 1458 })
  return pok, vel
end

local function group(sim, pok, vel)
  vel:slash("accept")
  pok:slash("invite Velvet")
  sim:advance(2)
end

T.test("two clients exchange PING over the channel and PONG by whisper", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  pok:slash("net")
  vel:slash("net")
  sim:advance(3)
  T.ok(logHas(pok, "received CHANNEL from Velvet Forever: PING|1|Velvet|Horde"))
  T.ok(logHas(vel, "received CHANNEL from Thalindra Forever: PING|1|Thalindra|Horde"))
  T.ok(logHas(pok, "received CHANNEL from Thalindra Forever: PING|1|Thalindra|Horde"), "own echo")
  T.ok(logHas(pok, "received WHISPER from Velvet Forever: PONG|1|Velvet|Horde"))
  T.ok(logHas(vel, "received WHISPER from Thalindra Forever: PONG|1|Thalindra|Horde"))
  T.eq(sentCount(pok, "^PONG", "Velvet Forever"), 1)
  T.eq(sentCount(vel, "^PONG", "Thalindra Forever"), 1)
  T.eq(sentCount(pok, "^PONG", "Thalindra Forever"), 0, "nobody PONGs itself")
  T.eq(sentCount(vel, "^PONG", "Velvet Forever"), 0, "nobody PONGs itself")
  T.eq(#sim.dropped, 0)
end)

T.test("a whisper to a short name is not delivered, to Name Realm it is", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  local send = pok.env.C_ChatInfo.SendAddonMessage
  send("PTX", "PING|1|Thalindra|Horde", "WHISPER", "Velvet")
  sim:advance(1)
  T.eq(vel.env.PortaxiDB.probe, nil, "nothing arrived")
  T.eq(sim.dropped[1].target, "Velvet")
  send("PTX", "PING|1|Thalindra|Horde", "WHISPER", "Velvet Forever")
  sim:advance(0.05)
  T.eq(vel.env.PortaxiDB.probe, nil, "not before the latency")
  sim:advance(0.05)
  T.ok(logHas(vel, "received WHISPER from Thalindra Forever: PING|1|Thalindra|Horde"))
  sim:advance(1)
  T.ok(logHas(pok, "received WHISPER from Velvet Forever: PONG|1|Velvet|"), "the reply came back")
end)

T.test("an unregistered prefix is not delivered", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  local got = recorder(vel, { "CHAT_MSG_ADDON" })
  pok.env.C_ChatInfo.SendAddonMessage("OTHER", "x", "WHISPER", "Velvet Forever")
  pok.env.C_ChatInfo.SendAddonMessage("PTX", "y", "WHISPER", "Velvet Forever")
  sim:advance(1)
  T.eq(got, { { "CHAT_MSG_ADDON", "PTX", "y", "WHISPER", "Thalindra Forever" } })
end)

T.test("invite and accept put both clients in each other's party", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  group(sim, pok, vel)
  T.eq(pok.party, { "Velvet" })
  T.eq(vel.party, { "Thalindra" })
  T.eq(pok.env.UnitName("party1"), "Velvet")
  T.eq(vel.env.UnitName("party1"), "Thalindra")
  T.eq(vel.env.UnitClass("party1"), "MAGE")
  T.ok(logHas(vel, "invite from Thalindra"))
  T.ok(logHas(pok, "in group: true, members: 2"))
  T.ok(logHas(vel, "in group: true, members: 2"))
  T.ok(vel.env.UnitIsConnected("party1"))
end)

T.test("a blocked invite never reaches the other client", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  pok.blocked["C_PartyInfo.InviteUnit"] = true
  group(sim, pok, vel)
  T.ok(logHas(pok, "protected call blocked: C_PartyInfo.InviteUnit()"))
  T.eq(vel.pendingInviter, nil)
  T.eq(#vel.party, 0)
  T.ok(not logHas(vel, "invite from"))
end)

T.test("leaving the group disbands it on the other side", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  group(sim, pok, vel)
  vel.env.C_PartyInfo.LeaveParty()
  T.eq(#pok.party, 1, "not before the latency")
  sim:advance(1)
  T.eq(#pok.party, 0)
  T.eq(pok.units.party1, nil)
  T.ok(logHas(pok, "in group: false, members: 0"))
end)

T.test("trade: prefilled gold reaches the other side and moves exactly on accept", function()
  local sim = Sim.new()
  local pok, vel = horde(sim)
  vel:setMoney(10000)
  vel:slash("trade 150")
  sim:target(pok, vel)
  pok:slash("opentrade")
  sim:advance(3)
  T.eq(pok.trade.with, "Velvet")
  T.eq(vel.trade.with, "Thalindra")
  T.eq(vel.trade.mine, 150)
  T.eq(pok.trade.theirs, 150)
  T.ok(logHas(pok, "money changed: mine 0g 0s 0c, theirs 0g 1s 50c"))
  local before = pok.player.money
  T.ok(sim:acceptTrade(pok, vel))
  T.eq(pok.player.money, before + 150)
  T.eq(vel.player.money, 10000 - 150)
  T.eq(pok.trade, nil)
  T.eq(vel.trade, nil)
  T.fails(function() sim:acceptTrade(pok, vel) end, "no open trade")
end)

T.test("closing the trade window closes it on the other side", function()
