-- The fake client itself: timers, forbidden calls, combat lockdown, isolation.
local T = dofile("tests/lib/t.lua")
local Wow = dofile("tests/lib/wowstub.lua")

T.test("timers run in due order, including ones scheduled meanwhile", function()
  local wow = Wow.new()
  local order = {}
  wow.env.C_Timer.After(2, function() order[#order + 1] = "b" end)
  wow.env.C_Timer.After(1, function()
    order[#order + 1] = "a"
    wow.env.C_Timer.After(0.5, function() order[#order + 1] = "a2" end)
  end)
  wow:advance(1.9)
  T.eq(order, { "a", "a2" })
  wow:advance(0.1)
  T.eq(order, { "a", "a2", "b" })
  T.eq(wow.clock, 1002)
end)

T.test("tickers repeat until cancelled or out of iterations", function()
  local wow = Wow.new()
  local n, m = 0, 0
  local ticker = wow.env.C_Timer.NewTicker(1, function() n = n + 1 end)
  wow.env.C_Timer.NewTicker(1, function() m = m + 1 end, 2)
  wow:advance(3)
  ticker:Cancel()
  wow:advance(3)
  T.eq(n, 3)
  T.eq(m, 2)
end)

T.test("timers can be cancelled", function()
  local wow = Wow.new()
  local ran = false
  local t = wow.env.C_Timer.NewTimer(1, function() ran = true end)
  t:Cancel()
  wow:advance(2)
  T.ok(not ran)
end)

T.test("forbidden calls raise an error (D10)", function()
  local wow = Wow.new()
  T.fails(function() wow.env.AcceptTrade() end, "forbidden call AcceptTrade")
  T.fails(function() wow.env.C_Container.UseContainerItem(0, 1) end, "forbidden call")
end)

T.test("secure attributes cannot change in combat", function()
  local wow = Wow.new()
  local b = wow.env.CreateFrame("Button", "PortaxiNextButton", wow.env.UIParent, "SecureActionButtonTemplate")
  b:SetAttribute("type", "spell")
  wow:setCombat(true)
  T.fails(function() b:SetAttribute("spell", 11417) end, "combat lockdown")
  wow:setCombat(false)
  b:SetAttribute("spell", 11417)
  b:Click()
  T.eq(wow.secureClicks[1], { type = "spell", spell = 11417 })
end)

T.test("unset widget state reads as nil, unknown methods are no-ops", function()
  local wow = Wow.new()
  local f = wow.env.CreateFrame("Button")
  T.eq(f:GetText(), nil)
  T.eq(f:GetTexture(), nil)
  T.eq(f:GetWidth(), 0)
  T.ok(f:IsEnabled(), "enabled until disabled")
  T.eq(f:SomeUnknownMethod(), nil)
end)

T.test("registering an event Forever does not know raises, as in game", function()
  local wow = Wow.new()
  local f = wow.env.CreateFrame("Frame")
  T.fails(function() f:RegisterEvent("LEARNED_SPELL_IN_TAB") end, "unknown event")
  f:RegisterEvent("SPELLS_CHANGED")
end)

T.test("PreClick runs before the secure action is recorded", function()
  local wow = Wow.new()
  local b = wow.env.CreateFrame("Button", "X", nil, "SecureActionButtonTemplate")
  b:SetScript("PreClick", function(self) self:SetAttribute("type", "item") end)
  b:Click()
  T.eq(wow.secureClicks[1].type, "item")
end)

T.test("the addon environment has no os or io, and clients are isolated", function()
  local a, b = Wow.new(), Wow.new()
  T.eq(a.env.os, nil)
  T.eq(a.env.io, nil)
  a.env.PortaxiDB = {}
  T.eq(b.env.PortaxiDB, nil)
end)

T.test("single client: channel echo arrives as Name Realm, whisper to own short name does not", function()
  local wow = Wow.new()
  local got = {}
  wow.env.C_ChatInfo.RegisterAddonMessagePrefix("PTX")
  local f = wow.env.CreateFrame("Frame")
  f:RegisterEvent("CHAT_MSG_ADDON")
  f:SetScript("OnEvent", function(_, _, prefix, msg, kind, sender) got[#got + 1] = { msg, kind, sender } end)
  wow.env.C_ChatInfo.SendAddonMessage("PTX", "a", "CHANNEL", 6)
  wow.env.C_ChatInfo.SendAddonMessage("PTX", "b", "WHISPER", "Thalindra")
  wow.env.C_ChatInfo.SendAddonMessage("PTX", "c", "WHISPER", "Thalindra Forever")
  wow:advance(1)
  T.eq(got, { { "a", "CHANNEL", "Thalindra Forever" }, { "c", "WHISPER", "Thalindra Forever" } })
  T.fails(function() wow.env.C_ChatInfo.SendAddonMessage("PTX", ("x"):rep(256), "CHANNEL", 6) end, "255")
end)

T.done()
